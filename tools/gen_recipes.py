#!/usr/bin/env python3
"""Generates CrafterArbitrage/Data/<Profession>.lua and Data/Items.lua from the trimmed wago tables.

Usage: python3 tools/gen_recipes.py        (reads tools/wago/*.csv, see tools/filter_wago.py)

Data/<Profession>.lua: one entry per craftable recipe (a spell that creates an item), keyed by spell id:
  name, out = { itemID, qty }, r = { { itemID, qty }, ... } reagents,
  orange / yellow / green / gray = skill levels where the recipe changes colour,
  acq = SkillLineAbility AcquireMethod, class / race masks only when the recipe is restricted,
  train = { skill needed, cost in copper } and trainers = { npc ids } when a trainer teaches it (tools/cmangos),
  ranks = { { rank, cost, skill needed, character level } } for the profession's own rank spells.
  recipeItems = { { itemID, vendors = { npc ids }, drops = { npc ids, a few }, objects = count, quests = { ids } } }
  for the items that teach it (tools/wago/RecipeItems.csv, sources from tools/questie).
Data/Sources.lua: Npcs[id] = { name, subtitle, faction, area, x, y } for those vendors and droppers, Quests[id] = name.
Data/Trainers.lua: trainer npc id -> name, subtitle, faction (A, H, AH), zone area id and x, y (percent of that
zone's map; tools/questie).
Data/Items.lua: every output and reagent item with its vendor sell price (copper), vendor buy price, quality,
  and bop = binds when picked up (cannot go on the auction house).
"""
import csv
from pathlib import Path

HERE = Path(__file__).resolve().parent
WAGO = HERE / "wago"
OUT = HERE.parent / "CrafterArbitrage" / "Data"

PROFESSIONS = {  # skill line -> file name; Mining (186) is only its smelting recipes
    "171": "Alchemy", "164": "Blacksmithing", "202": "Engineering", "165": "Leatherworking",
    "197": "Tailoring", "185": "Cooking", "129": "FirstAid", "186": "Smelting",
}
BIND_ON_PICKUP = "1"


def read(name, folder=WAGO):
    with open(folder / f"{name}.csv", encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def num(s, default=0):
    try:
        return int(float(s)) if s != "" else default
    except ValueError:
        return default


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    names = {r["ID"]: r["Name_lang"] for r in read("SpellName")}
    items = {r["ID"]: r for r in read("ItemSparse")}
    outputs = {}
    for r in read("SpellEffect"):
        # Several create-item effects on one spell are not plain crafts; take the first and flag nothing.
        outputs.setdefault(r["SpellID"], (r["EffectItemType"], max(1, num(r["EffectBasePointsF"], 1))))
    reagents = {}
    for r in read("SpellReagents"):
        reagents[r["SpellID"]] = [(r[f"Reagent_{i}"], num(r[f"ReagentCount_{i}"]))
                                  for i in range(8) if num(r[f"Reagent_{i}"]) > 0 and num(r[f"ReagentCount_{i}"]) > 0]

    # Trainers (tools/extract_cmangos.py): cheapest price and every NPC per recipe; rank spells per profession.
    taught, ranks, trainer_names = {}, {}, {}
    for r in read("trainer_spells", HERE / "cmangos"):
        trainer_names[r["npc"]] = (r["name"], r["subname"])
        if r["rank_step"]:
            key = (r["skill"], num(r["rank_step"]))
            cur = ranks.get(key)
            cand = (num(r["cost"]), num(r["reqskill"]), num(r["reqlevel"]))
            ranks[key] = cand if cur is None else min(cur, cand)
        else:
            t = taught.setdefault(r["spell"], {"cost": None, "skill": 0, "npcs": set()})
            cost = num(r["cost"])
            if t["cost"] is None or cost < t["cost"]:
                t["cost"], t["skill"] = cost, num(r["reqskill"])
            t["npcs"].add(num(r["npc"]))

    places = {r["npc"]: r for r in read("trainers", HERE / "questie")}

    # Recipe items and where they come from (tools/extract_questie.py).
    teachers = {}  # recipe spell -> [recipe item ids]
    for r in read("RecipeItems"):
        teachers.setdefault(r["spell"], []).append(r["item"])
    found = {}  # recipe item -> {kind: [ids]}
    for r in read("recipe_sources", HERE / "questie"):
        found.setdefault(r["item"], {}).setdefault(r["kind"], []).append(num(r["id"]))
    source_npcs = {r["npc"]: r for r in read("npcs", HERE / "questie")}
    source_quests = {r["id"]: r["name"] for r in read("quests", HERE / "questie")}
    used_npcs, used_quests = set(), set()

    OUT.mkdir(parents=True, exist_ok=True)
    used_items = set()
    for line, prof in PROFESSIONS.items():
        rows = [r for r in read("SkillLineAbility") if r["SkillLine"] == line and r["Spell"] in outputs]
        rows.sort(key=lambda r: (num(r["MinSkillLineRank"]), num(r["Spell"])))
        lines = [f"-- Generated by tools/gen_recipes.py ({prof}). Do not edit by hand.",
                 "-- Source: WoW Forever client tables from wago.tools, build "
                 + (WAGO / "BUILD").read_text().strip() + ".",
                 "local _, CA = ...", "CA.Data = CA.Data or {}", "",
                 f"CA.Data.{prof} = {{", f"  skillLine = {line},"]
        prof_ranks = sorted((step, v) for (sk, step), v in ranks.items() if sk == line)
        if prof_ranks:
            lines.append("  ranks = { -- { rank (1 apprentice .. 4 artisan), cost, skill needed, character level }")
            lines += [f"    {{ {step}, {c}, {sk}, {lv} }}," for step, (c, sk, lv) in prof_ranks]
            lines.append("  },")
        lines.append("  recipes = {")
        for r in rows:
            spell = r["Spell"]
            item, qty = outputs[spell]
            used_items.add(item)
            regs = reagents.get(spell, [])
            used_items.update(i for i, _ in regs)
            low, high = num(r["TrivialSkillLineRankLow"]), num(r["TrivialSkillLineRankHigh"])
            yellow = (low + high) // 2
            fields = [f"name = {lua_str(names.get(spell, ''))}", f"out = {{ {item}, {qty} }}",
                      "r = { " + ", ".join(f"{{ {i}, {n} }}" for i, n in regs) + " }",
                      f"orange = {num(r['MinSkillLineRank'])}", f"yellow = {yellow}", f"green = {low}", f"gray = {high}"]
            if num(r["AcquireMethod"]):
                fields.append(f"acq = {num(r['AcquireMethod'])}")
            t = taught.get(spell)
            if t:
                fields.append(f"train = {{ {t['skill']}, {t['cost']} }}")
                fields.append("trainers = { " + ", ".join(str(n) for n in sorted(t["npcs"])) + " }")
            book = []
            for ritem in sorted(teachers.get(spell, []), key=int):
                used_items.add(ritem)
                f = found.get(ritem, {})
                parts = [ritem]
                if f.get("vendor"):
                    parts.append("vendors = { " + ", ".join(map(str, f["vendor"])) + " }")
                    used_npcs.update(f["vendor"])
                if f.get("drop"):
                    parts.append("drops = { " + ", ".join(map(str, f["drop"])) + " }")
                    used_npcs.update(f["drop"])
                if f.get("object"):
                    parts.append(f"objects = {len(f['object'])}")
                if f.get("quest"):
                    parts.append("quests = { " + ", ".join(map(str, f["quest"])) + " }")
                    used_quests.update(f["quest"])
                book.append("{ " + ", ".join(map(str, parts)) + " }")
            if book:
                fields.append("recipeItems = { " + ", ".join(book) + " }")
            if num(r["ClassMask"]):
                fields.append(f"classMask = {num(r['ClassMask'])}")
            if num(r["RaceMasks_0"]) or num(r["RaceMasks_1"]):
                fields.append(f"raceMask = {{ {num(r['RaceMasks_0'])}, {num(r['RaceMasks_1'])} }}")
            lines.append(f"    [{spell}] = {{ " + ", ".join(fields) + " },")
        lines += ["  },", "}", ""]
        (OUT / f"{prof}.lua").write_text("\n".join(lines), encoding="utf-8")
        print(f"{prof}: {len(rows)} recipes")

    lines = ["-- Generated by tools/gen_recipes.py. Do not edit by hand.", "local _, CA = ...", "CA.Data = CA.Data or {}", "",
             "CA.Data.Npcs = { -- npc id = { name, subtitle, faction, area id, x, y }"]
    for npc in sorted(used_npcs):
        r = source_npcs.get(str(npc))
        if not r:
            continue
        where = f", {r['area']}, {r['x']}, {r['y']}" if r["area"] else ""
        lines.append(f"  [{npc}] = {{ {lua_str(r['name'])}, {lua_str(r['subname'])}, {lua_str(r['faction'])}{where} }},")
    lines += ["}", "", "CA.Data.Quests = { -- quest id = name"]
    for q in sorted(used_quests):
        lines.append(f"  [{q}] = {lua_str(source_quests.get(str(q), ''))},")
    lines += ["}", ""]
    (OUT / "Sources.lua").write_text("\n".join(lines), encoding="utf-8")
    print("Sources:", len(used_npcs), "npcs,", len(used_quests), "quests")

    used_npcs = sorted({n for t in taught.values() for n in t["npcs"]})
    lines = ["-- Generated by tools/gen_recipes.py. Do not edit by hand.", "local _, CA = ...", "CA.Data = CA.Data or {}", "",
             "CA.Data.Trainers = { -- npc id = { name, subtitle, faction, area id, x, y }"]
    for npc in used_npcs:
        name, sub = trainer_names.get(str(npc), ("", ""))
        p = places.get(str(npc), {})
        where = f", {p['area']}, {p['x']}, {p['y']}" if p.get("area") else ""
        lines.append(f"  [{npc}] = {{ {lua_str(name)}, {lua_str(sub)}, {lua_str(p.get('faction', ''))}{where} }},")
    lines += ["}", ""]
    (OUT / "Trainers.lua").write_text("\n".join(lines), encoding="utf-8")
    print("Trainers:", len(used_npcs))

    lines = ["-- Generated by tools/gen_recipes.py. Do not edit by hand.",
             "-- sell / buy = vendor prices in copper; bop = binds when picked up (not tradable on the AH).",
             "local _, CA = ...", "CA.Data = CA.Data or {}", "", "CA.Data.Items = {"]
    unknown = []
    for item in sorted(used_items, key=int):
        r = items.get(item)
        if not r:
            unknown.append(item)  # not in the client table (new Forever item?): the addon asks the game instead
            continue
        fields = [f"name = {lua_str(r['Display_lang'])}", f"sell = {num(r['SellPrice'])}", f"buy = {num(r['BuyPrice'])}",
                  f"quality = {num(r['OverallQualityID'])}"]
        if r["Bonding"] == BIND_ON_PICKUP:
            fields.append("bop = true")
        lines.append(f"  [{item}] = {{ " + ", ".join(fields) + " },")
    lines += ["}", ""]
    (OUT / "Items.lua").write_text("\n".join(lines), encoding="utf-8")
    print(f"Items: {len(used_items) - len(unknown)} with prices, {len(unknown)} not in ItemSparse")


if __name__ == "__main__":
    main()
