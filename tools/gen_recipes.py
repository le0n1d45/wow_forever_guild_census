#!/usr/bin/env python3
"""Generates CrafterArbitrage/Data/<Profession>.lua and Data/Items.lua from the trimmed wago tables.

Usage: python3 tools/gen_recipes.py        (reads tools/wago/*.csv, see tools/filter_wago.py)

Data/<Profession>.lua: one entry per craftable recipe (a spell that creates an item), keyed by spell id:
  name, out = { itemID, qty }, r = { { itemID, qty }, ... } reagents,
  orange / yellow / green / gray = skill levels where the recipe changes colour,
  acq = SkillLineAbility AcquireMethod, class / race masks only when the recipe is restricted.
Data/Items.lua: every output and reagent item with its vendor sell price (copper), vendor buy price, quality,
  and bop = binds when picked up (cannot go on the auction house).
"""
import csv
from pathlib import Path

HERE = Path(__file__).resolve().parent
WAGO = HERE / "wago"
OUT = HERE.parent / "CrafterArbitrage" / "Data"

PROFESSIONS = {  # skill line -> file name; Mining (186) is only its smelting recipes
    "171": "Alchemy", "164": "Blacksmithing", "202": "Engineering", "165": "Leatherworking",
    "197": "Tailoring", "185": "Cooking", "129": "FirstAid", "186": "Smelting",
}
BIND_ON_PICKUP = "1"


def read(name):
    with open(WAGO / f"{name}.csv", encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def num(s, default=0):
    try:
        return int(float(s)) if s != "" else default
    except ValueError:
        return default


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    names = {r["ID"]: r["Name_lang"] for r in read("SpellName")}
    items = {r["ID"]: r for r in read("ItemSparse")}
    outputs = {}
    for r in read("SpellEffect"):
        # Several create-item effects on one spell are not plain crafts; take the first and flag nothing.
        outputs.setdefault(r["SpellID"], (r["EffectItemType"], max(1, num(r["EffectBasePointsF"], 1))))
    reagents = {}
    for r in read("SpellReagents"):
        reagents[r["SpellID"]] = [(r[f"Reagent_{i}"], num(r[f"ReagentCount_{i}"]))
                                  for i in range(8) if num(r[f"Reagent_{i}"]) > 0 and num(r[f"ReagentCount_{i}"]) > 0]

    OUT.mkdir(parents=True, exist_ok=True)
    used_items = set()
    for line, prof in PROFESSIONS.items():
        rows = [r for r in read("SkillLineAbility") if r["SkillLine"] == line and r["Spell"] in outputs]
        rows.sort(key=lambda r: (num(r["MinSkillLineRank"]), num(r["Spell"])))
        lines = [f"-- Generated by tools/gen_recipes.py ({prof}). Do not edit by hand.",
                 "-- Source: WoW Forever client tables from wago.tools, build "
                 + (WAGO / "BUILD").read_text().strip() + ".",
                 "local _, CA = ...", "CA.Data = CA.Data or {}", "",
                 f"CA.Data.{prof} = {{", f"  skillLine = {line},", "  recipes = {"]
        for r in rows:
            spell = r["Spell"]
            item, qty = outputs[spell]
            used_items.add(item)
            regs = reagents.get(spell, [])
            used_items.update(i for i, _ in regs)
            low, high = num(r["TrivialSkillLineRankLow"]), num(r["TrivialSkillLineRankHigh"])
            yellow = (low + high) // 2
            fields = [f"name = {lua_str(names.get(spell, ''))}", f"out = {{ {item}, {qty} }}",
                      "r = { " + ", ".join(f"{{ {i}, {n} }}" for i, n in regs) + " }",
                      f"orange = {num(r['MinSkillLineRank'])}", f"yellow = {yellow}", f"green = {low}", f"gray = {high}"]
            if num(r["AcquireMethod"]):
                fields.append(f"acq = {num(r['AcquireMethod'])}")
            if num(r["ClassMask"]):
                fields.append(f"classMask = {num(r['ClassMask'])}")
            if num(r["RaceMasks_0"]) or num(r["RaceMasks_1"]):
                fields.append(f"raceMask = {{ {num(r['RaceMasks_0'])}, {num(r['RaceMasks_1'])} }}")
            lines.append(f"    [{spell}] = {{ " + ", ".join(fields) + " },")
        lines += ["  },", "}", ""]
        (OUT / f"{prof}.lua").write_text("\n".join(lines), encoding="utf-8")
        print(f"{prof}: {len(rows)} recipes")

    lines = ["-- Generated by tools/gen_recipes.py. Do not edit by hand.",
             "-- sell / buy = vendor prices in copper; bop = binds when picked up (not tradable on the AH).",
             "local _, CA = ...", "CA.Data = CA.Data or {}", "", "CA.Data.Items = {"]
    unknown = []
    for item in sorted(used_items, key=int):
        r = items.get(item)
        if not r:
            unknown.append(item)  # not in the client table (new Forever item?): the addon asks the game instead
            continue
        fields = [f"name = {lua_str(r['Display_lang'])}", f"sell = {num(r['SellPrice'])}", f"buy = {num(r['BuyPrice'])}",
                  f"quality = {num(r['OverallQualityID'])}"]
        if r["Bonding"] == BIND_ON_PICKUP:
            fields.append("bop = true")
        lines.append(f"  [{item}] = {{ " + ", ".join(fields) + " },")
    lines += ["}", ""]
    (OUT / "Items.lua").write_text("\n".join(lines), encoding="utf-8")
    print(f"Items: {len(used_items) - len(unknown)} with prices, {len(unknown)} not in ItemSparse")


if __name__ == "__main__":
    main()
